let sus = 100;

function setup() {
	createCanvas(800, 500);
	rectMode(CENTER);
	noStroke();
	for (const s of nothing_to_see_here) { for (const a of s) { for (const p of a) { if (p === "1") {
		ugly_variable_collection[2].push({x: random(-500, 500),y: random(-500, 500),multiplier: floor(random(1, sus))
	});}}}}
}

let ugly_variable_collection = [3, 0.3, []]

function draw() {
	background(24, 28, 48);
	noStroke();
	sanity_drain();
	fill("white");
	textSize(40);
	stroke(0);
	strokeWeight(10);
	text("How many 'give'?", 300, 50);
}

// WARNING: Reading beyond this will cause sanity drain at at least 5% per second.
function sanity_drain(){
	const c = 4.8;
	const lh = c * 9;
	const th = lh * nothing_to_see_here.length;
	const fY = (height - th) / 2;
	const elSec = sus / 2 + millis() / 1000;
	let pI = 0;

	for (let li = 0; li < nothing_to_see_here.length; li++) {
		const r = nothing_to_see_here[li];
		const lw = r[0].length * c;
		const fX = (width - lw) / 2;
		const y = fY + li * lh;

		for (let row = 0; row < r.length; row++) {
			for (let column = 0; column < r[row].length; column++) {
				if (r[row][column] !== "1") {
					continue;
				}

				const ofs = ugly_variable_collection[2][pI++];
				const pcs = ugly_variable_collection[0] * ofs.multiplier;
				const ct = elSec % pcs;
				const mt = pcs - ugly_variable_collection[1];
				const move = ct < ugly_variable_collection[1]
					? 0
					: (1 - cos(TWO_PI * (ct - ugly_variable_collection[1]) / mt)) / 2;
				const px = fX + column * c + ofs.x * move;
				const py = y + row * c + ofs.y * move;
				fill(120 + li * 25, 205, 255);

				push();
				translate(px, py);
				if ((column + row + li) % 4 === 0) {
					ellipse(0, 0, c * 0.82, c * 0.82);
				} else {
					rotate(((column + row) % 2 === 0 ? 1 : -1) * 0.12);
					rect(0, 0, c * 0.88, c * 0.88);
				}
				pop();
			}
		}
	}
}